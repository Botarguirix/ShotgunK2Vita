"""Package only executable VPKs, symbols and review evidence; never game data."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import uuid
import zipfile
from validate_vpk import validate
from iteration_manifest import finalize

root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--vpk-only',action='store_true',required=True)
p.add_argument('--steam-build',type=Path,default=root/'build-iterations/00.78-steam-alpha')
p.add_argument('--legacy-build',type=Path,default=root/'build-iterations/00.78-legacy-alpha')
p.add_argument('--output',type=Path,help='New, nonexistent delivery directory')
a=p.parse_args()
version=re.search(r'set\(SG_BUILD_VERSION "([^"]+)"\)',(root/'CMakeLists.txt').read_text()).group(1)
items=[('steam',a.steam_build,'ShotgunKing2Vita-steam.vpk','SGKV00002'),('1.5',a.legacy_build,'ShotgunKing2Vita-performance.vpk','SGKV00001')]
checks={}
for variant,build,name,title in items:
    record=validate(build/name,require_art=True)
    if record['sfo'].get('TITLE_ID')!=title or record['sfo'].get('APP_VER')!=version:raise ValueError('Unexpected SFO identity')
    header=build/'generated/code_patches.h'
    if variant=='steam' and (not header.is_file() or '#define SG_CODE_PATCH_COUNT 0' not in header.read_text()):
        raise ValueError('Public packaging requires zero private code patches')
    with zipfile.ZipFile(build/name) as z:
        allowed={'eboot.bin','sce_sys/param.sfo','sce_sys/icon0.png','sce_sys/pic0.png','sce_sys/livearea/contents/bg0.png','sce_sys/livearea/contents/startup.png','sce_sys/livearea/contents/template.xml','performance.cfg'}
        if not set(z.namelist())<=allowed:raise ValueError('Unexpected VPK content')
        if z.read('eboot.bin')[:4]!=b'SCE\0':raise ValueError('Invalid SELF header')
    # Permit only the neutral images generated by this project, never private game art.
    for asset in ['icon0.png','pic0.png','livearea/contents/bg0.png','livearea/contents/startup.png','livearea/contents/template.xml']:
        with zipfile.ZipFile(build/name) as z:
            if z.read('sce_sys/'+asset)!=(root/'private/livearea'/asset).read_bytes():raise ValueError('Non-neutral artwork')
    checks[variant]=record
out=a.output or root/'artifacts/prereleases/v0.78-alpha'/('run-'+uuid.uuid4().hex)
out.mkdir(parents=True,exist_ok=False)
for variant,build,name,title in items:
    shutil.copy2(build/name,out/name)
    debug=out/'debug'/variant;debug.mkdir(parents=True)
    for source,target in [('ShotgunKing2Vita','ShotgunKing2Vita.elf'),('ShotgunKing2Vita.map','ShotgunKing2Vita.map')]:shutil.copy2(build/source,debug/target)
snapshot=out/'source';snapshot.mkdir()
git=['git','-c','safe.directory='+root.as_posix(),'-C',str(root)]
if subprocess.check_output([*git,'status','--porcelain'],text=True).strip():
    raise ValueError('Commit the clean release tree before packaging')
tracked=subprocess.check_output([*git,'ls-files','-z']).decode().split('\0')
for name in filter(None,tracked):
    source=root/name
    if not source.is_file():raise ValueError('Missing tracked source file: '+name)
    target=snapshot/name;target.parent.mkdir(parents=True,exist_ok=True)
    shutil.copy2(source,target)
(out/'validation.json').write_text(json.dumps(checks,indent=2),encoding='utf-8')
(out/'iteration.json').write_text(json.dumps({'version':version,'release':'0.78 alpha','upload_only':[item[2] for item in items]},indent=2))
finalize(root,out,version,evidence_dir=root/'reports/release-0.78-alpha')
print(str(out))
